namespace {

ULONG_PTR g_gdiplusToken = 0;

std::string toUpper(std::string s) {
    for (char& c : s) c = (char)std::toupper((unsigned char)c);
    return s;
}

// File name without directory and extension, as UTF-8.
std::string fileStem(const std::wstring& path) {
    size_t slash = path.find_last_of(L"\\/");
    std::wstring name = slash == std::wstring::npos ? path : path.substr(slash + 1);
    size_t dot = name.find_last_of(L'.');
    if (dot != std::wstring::npos) name = name.substr(0, dot);
    std::string out;
    for (wchar_t c : name) out += (c < 128) ? (char)c : '_';
    return out;
}

void put16(std::vector<uint8_t>& v, uint16_t x) {
    v.push_back((uint8_t)(x & 0xFF));
    v.push_back((uint8_t)(x >> 8));
}

void put32(std::vector<uint8_t>& v, uint32_t x) {
    for (int i = 0; i < 4; ++i) v.push_back((uint8_t)(x >> (8 * i)));
}

} // namespace

bool initImageIO() {
    Gdiplus::GdiplusStartupInput input;
    return Gdiplus::GdiplusStartup(&g_gdiplusToken, &input, nullptr) == Gdiplus::Ok;
}

void shutdownImageIO() {
    if (g_gdiplusToken) Gdiplus::GdiplusShutdown(g_gdiplusToken);
    g_gdiplusToken = 0;
}

bool loadImage(const std::wstring& path, Image& out, std::wstring& error) {
    Gdiplus::Bitmap bmp(path.c_str());
    if (bmp.GetLastStatus() != Gdiplus::Ok) {
        error = L"Cannot open the image (unsupported format or file is damaged).";
        return false;
    }
    const int w = (int)bmp.GetWidth();
    const int h = (int)bmp.GetHeight();
    if (w <= 0 || h <= 0) {
        error = L"The image is empty.";
        return false;
    }

    Gdiplus::Rect rect(0, 0, w, h);
    Gdiplus::BitmapData data;
    if (bmp.LockBits(&rect, Gdiplus::ImageLockModeRead, PixelFormat32bppARGB, &data) != Gdiplus::Ok) {
        error = L"Cannot read the image pixels.";
        return false;
    }

    out.w = w;
    out.h = h;
    out.px.resize((size_t)w * h);
    for (int y = 0; y < h; ++y) {
        const uint32_t* row = (const uint32_t*)((const uint8_t*)data.Scan0 + (ptrdiff_t)y * data.Stride);
        for (int x = 0; x < w; ++x) {
            const uint32_t p = row[x];
            const uint32_t a = p >> 24;
            uint32_t r = (p >> 16) & 0xFF, g = (p >> 8) & 0xFF, b = p & 0xFF;
            if (a != 255) {
                // Composite onto white paper.
                r = (r * a + 255 * (255 - a)) / 255;
                g = (g * a + 255 * (255 - a)) / 255;
                b = (b * a + 255 * (255 - a)) / 255;
            }
            out.px[(size_t)y * w + x] = 0xFF000000u | (r << 16) | (g << 8) | b;
        }
    }
    bmp.UnlockBits(&data);
    return true;
}

std::string toCIdentifier(const std::string& name) {
    std::string out;
    for (char c : name) {
        const unsigned char u = (unsigned char)c;
        out += (std::isalnum(u) || c == '_') ? c : '_';
    }
    if (out.empty()) out = "pictogram";
    if (std::isdigit((unsigned char)out[0])) out = "_" + out;
    return out;
}

bool saveAsCArray(const std::wstring& path, const std::vector<Pictogram>& pictos,
                  const std::vector<std::string>& names, std::wstring& error) {
    FILE* f = _wfopen(path.c_str(), L"wb");
    if (!f) {
        error = L"Cannot create the file.";
        return false;
    }

    const std::string stem = toCIdentifier(fileStem(path));
    const std::string guard = toUpper(stem) + "_H";

    const std::string upStem = toUpper(stem);

    std::fprintf(f, "/*\n");
    std::fprintf(f, " * Generated by Pictogram Parser\n");
    std::fprintf(f, " * %u pictogram(s)\n", (unsigned)pictos.size());
    std::fprintf(f, " *\n");
    std::fprintf(f, " * Every pictogram has a format (see the *_FORMAT_* defines and the table at the end):\n");
    std::fprintf(f, " *\n");
    std::fprintf(f, " * MONO1  - uint8_t[], 1 bit per pixel, row by row (top to bottom), MSB = leftmost pixel.\n");
    std::fprintf(f, " *          Every row is padded to a whole byte: bytes per row = (width + 7) / 8.\n");
    std::fprintf(f, " *          Bit = 1 -> black (ink) pixel, bit = 0 -> white (background) pixel.\n");
    std::fprintf(f, " * RGB565 - uint16_t[], one pixel per value, row by row, left to right:\n");
    std::fprintf(f, " *          bits 15-11 red, 10-5 green, 4-0 blue.\n");
    std::fprintf(f, " */\n\n");
    std::fprintf(f, "#ifndef %s\n#define %s\n\n#include <stdint.h>\n\n", guard.c_str(), guard.c_str());
    std::fprintf(f, "#define %s_FORMAT_MONO1  0\n#define %s_FORMAT_RGB565 1\n\n", upStem.c_str(), upStem.c_str());

    for (size_t i = 0; i < pictos.size(); ++i) {
        const Pictogram& p = pictos[i];
        const std::string id = toCIdentifier(names[i]);
        const std::string up = toUpper(id);

        std::fprintf(f, "#define %s_WIDTH  %d\n", up.c_str(), p.w);
        std::fprintf(f, "#define %s_HEIGHT %d\n", up.c_str(), p.h);
        std::fprintf(f, "#define %s_FORMAT %s_FORMAT_%s\n", up.c_str(), upStem.c_str(), p.color ? "RGB565" : "MONO1");

        if (p.color) {
            std::fprintf(f, "static const uint16_t %s[%d] = {\n", id.c_str(), p.w * p.h);
            for (int y = 0; y < p.h; ++y) {
                std::fprintf(f, "    ");
                for (int x = 0; x < p.w; ++x) {
                    const uint32_t c = p.rgb[(size_t)y * p.w + x];
                    const unsigned r = (c >> 16) & 0xFF, g = (c >> 8) & 0xFF, b = c & 0xFF;
                    const unsigned v565 = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
                    std::fprintf(f, "0x%04X,%s", v565, x + 1 < p.w ? " " : "");
                }
                std::fprintf(f, "\n");
            }
            std::fprintf(f, "};\n\n");
            continue;
        }

        const int bpr = (p.w + 7) / 8;
        std::fprintf(f, "static const uint8_t %s[%d] = {\n", id.c_str(), bpr * p.h);
        for (int y = 0; y < p.h; ++y) {
            std::fprintf(f, "    ");
            for (int bx = 0; bx < bpr; ++bx) {
                uint8_t byte = 0;
                for (int bit = 0; bit < 8; ++bit) {
                    const int x = bx * 8 + bit;
                    if (x < p.w && p.bits[(size_t)y * p.w + x]) byte |= (uint8_t)(0x80 >> bit);
                }
                std::fprintf(f, "0x%02X,", byte);
                if (bx + 1 < bpr) std::fprintf(f, " ");
            }
            // ASCII preview of the row
            std::fprintf(f, "  /* ");
            for (int x = 0; x < p.w; ++x) std::fputc(p.bits[(size_t)y * p.w + x] ? '#' : '.', f);
            std::fprintf(f, " */\n");
        }
        std::fprintf(f, "};\n\n");
    }

    // Lookup table of all pictograms. data points to uint8_t[] (MONO1) or uint16_t[] (RGB565).
    std::fprintf(f, "typedef struct {\n    const char *name;\n    uint16_t width;\n    uint16_t height;\n    uint8_t format;\n    const void *data;\n} %s_pictogram_t;\n\n", stem.c_str());
    std::fprintf(f, "#define %s_COUNT %u\n\n", upStem.c_str(), (unsigned)pictos.size());
    std::fprintf(f, "static const %s_pictogram_t %s_table[%u] = {\n", stem.c_str(), stem.c_str(), pictos.empty() ? 1u : (unsigned)pictos.size());
    for (size_t i = 0; i < pictos.size(); ++i) {
        const std::string id = toCIdentifier(names[i]);
        std::fprintf(f, "    { \"%s\", %d, %d, %s_FORMAT_%s, %s },\n", id.c_str(), pictos[i].w, pictos[i].h,
                     upStem.c_str(), pictos[i].color ? "RGB565" : "MONO1", id.c_str());
    }
    std::fprintf(f, "};\n\n#endif /* %s */\n", guard.c_str());

    const bool ok = std::ferror(f) == 0;
    std::fclose(f);
    if (!ok) error = L"Error while writing the file.";
    return ok;
}

// Writes a 1-bit BMP (black ink on white) or, for a colour pictogram, a 24-bit BMP.
bool saveAsBitmap(const std::wstring& path, const Pictogram& p, std::wstring& error) {
    const int bpp = p.color ? 24 : 1;
    const int rowBytes = ((p.w * bpp + 31) / 32) * 4;      // rows are padded to 4 bytes
    const uint32_t paletteBytes = p.color ? 0 : 2 * 4;      // 1 bpp needs a 2-colour palette
    const uint32_t pixelBytes = (uint32_t)rowBytes * p.h;
    const uint32_t headerSize = 14 + 40 + paletteBytes;     // file header + info header + palette

    std::vector<uint8_t> v;
    v.reserve(headerSize + pixelBytes);
    // BITMAPFILEHEADER
    v.push_back('B');
    v.push_back('M');
    put32(v, headerSize + pixelBytes);
    put16(v, 0);
    put16(v, 0);
    put32(v, headerSize);
    // BITMAPINFOHEADER
    put32(v, 40);
    put32(v, (uint32_t)p.w);
    put32(v, (uint32_t)p.h);   // positive -> bottom-up
    put16(v, 1);
    put16(v, (uint16_t)bpp);
    put32(v, 0);               // BI_RGB
    put32(v, pixelBytes);
    put32(v, 2835);            // 72 DPI
    put32(v, 2835);
    put32(v, p.color ? 0 : 2);
    put32(v, p.color ? 0 : 2);
    if (!p.color) {
        // Palette: index 0 = white, index 1 = black
        put32(v, 0x00FFFFFF);
        put32(v, 0x00000000);
    }
    // Pixels, bottom row first
    for (int y = p.h - 1; y >= 0; --y) {
        std::vector<uint8_t> row((size_t)rowBytes, 0);
        for (int x = 0; x < p.w; ++x) {
            if (p.color) {
                const uint32_t c = p.rgb[(size_t)y * p.w + x];
                row[(size_t)x * 3 + 0] = (uint8_t)(c & 0xFF);          // B
                row[(size_t)x * 3 + 1] = (uint8_t)((c >> 8) & 0xFF);   // G
                row[(size_t)x * 3 + 2] = (uint8_t)((c >> 16) & 0xFF);  // R
            } else if (p.bits[(size_t)y * p.w + x]) {
                row[(size_t)x / 8] |= (uint8_t)(0x80 >> (x % 8));
            }
        }
        v.insert(v.end(), row.begin(), row.end());
    }

    FILE* f = _wfopen(path.c_str(), L"wb");
    if (!f) {
        error = L"Cannot create " + path;
        return false;
    }
    const bool ok = std::fwrite(v.data(), 1, v.size(), f) == v.size();
    std::fclose(f);
    if (!ok) error = L"Error while writing " + path;
    return ok;
}
